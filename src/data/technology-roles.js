/** Look up a short role for a technology name, or null when we have none. */
export const roleForTechnology = (name) => roles[name] || null

/**
 * Deterministic icon per technology, so the “Key parts” stack reads visually
 * without hand-labelling all 700+ tool names.
 */
export function iconForTechnology(name) {
  const n = String(name).toLowerCase()
  if (/(sql|postgres|mysql|maria|mongo|redis|cassandra|dynamo|neo4j|database|orm|prisma|sequelize|sqlite|qdrant|pinecone|weaviate|faiss|vector)/.test(n))
    return 'database'
  if (/(docker|container|kubernetes|helm|podman|pod|eks|gke|aks)/.test(n)) return 'box'
  if (/(aws|azure|cloud|gcp|heroku|render|railway|firebase|supabase|s3|blob|bucket)/.test(n)) return 'cloud'
  if (/(js|javascript|typescript|react|vue|svelte|angular|html|css|tailwind|bootstrap|sass|postcss|vite|webpack)/.test(n))
    return 'window'
  if (/(python|java|rust|golang|^go$|c\+\+|c#|php|ruby|haskell|bash)/.test(n)) return 'fileCode'
  if (/(git|github|gitlab|bitbucket|merge|pull request|version)/.test(n)) return 'gitBranch'
  if (/(test|jest|vitest|playwright|junit|pytest|mocha|supertest)/.test(n)) return 'checkCircle'
  if (/(monitor|grafana|datadog|sentry|prometheus|loki|log|metric|observ)/.test(n)) return 'chart'
  if (/(queue|kafka|rabbit|sqs|celery|bullmq|stream)/.test(n)) return 'flow'
  if (/(nginx|apache|server|gunicorn|uvicorn|proxy|load balanc)/.test(n)) return 'server'
  if (/(tls|ssl|crypt|hash|bcrypt|argon|secrets|vault|key|fido|mfa|auth)/.test(n)) return 'lock'
  if (/(torch|tensor|model|llm|ollama|llama|gpt|transformer|onnx|gpu|cuda|tpu|neural)/.test(n)) return 'brain'
  if (/(dns|http|network|tcp|udp|ipv|dhcp|nat|wireguard|vpn|proxy)/.test(n)) return 'network'
  if (/(jira|linear|trello|notion|story|scrum|kanban|agile)/.test(n)) return 'users'
  return 'package'
}
